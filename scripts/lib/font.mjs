/** Throws on the first character that has no glyph, so a typo never renders as a blank. */
export function assertGlyphs(text) {
  for (const ch of text) {
    if (!GLYPHS[ch]) throw new Error(`missing glyph: "${ch}"`);
  }
}

const glyphId = (ch) => `g${ch.codePointAt(0).toString(16)}`;

/** Path data for one glyph, one rectangle per horizontal run of lit pixels. */
function glyphPath(rows) {
  let d = "";
  rows.forEach((row, y) => {
    for (const m of row.matchAll(/#+/g)) d += `M${m.index} ${y}h${m[0].length}v1h-${m[0].length}z`;
  });
  return d;
}

/** <path> definitions for every distinct visible character of `text`, ready for a <defs> block. */
export function glyphDefs(text) {
  assertGlyphs(text);
  const unique = [...new Set(text)].filter((ch) => ch !== " ");
  return unique.map((ch) => `<path id="${glyphId(ch)}" d="${glyphPath(GLYPHS[ch])}"/>`).join("");
}

/** <path> definitions for every glyph referenced by `<use href="#g..">` anywhere in `markup`. */
export function glyphDefsFor(markup) {
  const ids = new Set([...markup.matchAll(/href="#g([0-9a-f]+)"/g)].map((m) => m[1]));
  const chars = [...ids].map((hex) => String.fromCodePoint(parseInt(hex, 16))).join("");
  return glyphDefs(chars);
}

/** One <use> per visible character, with the text's top-left corner at (x, y). */
export function textUses(text, x, y, px, fill) {
  assertGlyphs(text);
  let out = "";
  [...text].forEach((ch, i) => {
    if (ch === " ") return;
    out += `<use href="#${glyphId(ch)}" transform="translate(${round(x + i * ADVANCE * px)} ${round(y)}) scale(${px})" fill="${fill}"/>`;
  });
  return out;
}

/** Width of `text` in user units at pixel size `px`. */
export function textWidth(text, px) {
  const len = [...text].length;
  return len === 0 ? 0 : (len * ADVANCE - 1) * px;
}

export const round = (n) => Math.round(n * 100) / 100;
